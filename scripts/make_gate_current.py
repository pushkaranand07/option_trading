"""Build docs/gate_current.md: the rules in force, copied from the frozen files, with each file's hash. It changes no rule.

    python scripts/make_gate_current.py

Hashes are the repo's own: sha256 of the parsed JSON with sorted keys, so line endings do not change them.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

# file, written, kind, results seen before it was written
SOURCES = [
    ("gate_v1.json", "2026-10-30", "gate", "SD for X_h and the minimum-move check, data to 2022. No model"),
    ("gate_v2.json", "2026-10-30", "gate", "Gate v1 self-tests and baselines; skip-rule diagnostics. No model"),
    ("gate_v2_addendum_1.json", "2026-10-30", "addendum", "Gate v2 baselines, including validation. No model"),
    ("features_v1.json", "2026-10-30", "spec", "Same, plus the option-chain parity flag rates. No model"),
    ("gate_v2_addendum_2.json", "2026-10-30", "addendum", "Same, plus power with and without item c. No model"),
    ("gate_v2_addendum_3.json", "2026-10-31", "addendum", "Same, plus baselines on D-1, including validation. No model"),
    ("gate_v2_addendum_4.json", "2026-10-31", "addendum", "Same, plus baselines on 20 schedules, including validation. No model"),
    ("gate_v2_addendum_5.json", "2026-10-31", "addendum", "Same. No model"),
    ("gate_v2_addendum_6.json", "2026-10-31", "addendum", "Same. No model"),
    ("models_v1.json", "2026-10-31", "spec", "Same. No model"),
    ("gate_v2_addendum_7.json", "2026-10-31", "addendum", "**Development results of the first model run.** It fixed a bug and changed no rule"),
    ("ai_strategist_test_v1.json", "2026-10-31", "spec", "Model suite verdict, power from 2019-2022. No AI trade counted"),
]


def canonical_hash(path: Path) -> str:
    d = json.loads(path.read_text(encoding="utf-8"))
    return hashlib.sha256(json.dumps(d, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")).hexdigest()


def load(name: str) -> dict:
    return json.loads((ROOT / "docs" / name).read_text(encoding="utf-8"))


def build() -> str:
    g2, a1, a2, a3, a4, a5, a6, a7, m = (load(n) for n in ("gate_v2.json", "gate_v2_addendum_1.json", "gate_v2_addendum_2.json", "gate_v2_addendum_3.json", "gate_v2_addendum_4.json", "gate_v2_addendum_5.json", "gate_v2_addendum_6.json", "gate_v2_addendum_7.json", "models_v1.json"))
    g = g2["gate"]
    x = g["g"]["x_h_percent"]
    block = g["d"]["block_dates_by_h"]
    pct = a5["item_d"]["lower_bound_percentile"]
    out = ["# Current gate", "", "> **Status:** Read-only summary, generated by `scripts/make_gate_current.py`. **It changes no rule; if it differs from a frozen file, the frozen file wins.**", "> **Scope:** the rules in force for a futures model, and every file they come from.", "",
           "Research and decision support only, not investment advice. **Cost model unverified.** Quoted text is copied from the frozen files.", "",
           "## The pass", "", f"Items {', '.join(a5['pass_condition']['items'])} must all pass, at 1.5x costs. Items {' and '.join(a5['pass_condition']['report_only'])} are report-only.", "",
           "| Item | Rule | Source |", "|---|---|---|",
           f"| a | {g['a']} | gate_v2 |",
           f"| d | {g['d']['rule']}. Percentile by forward specs: {pct['1_spec']}, {pct['2_specs']}, {round(pct['3_specs'], 4)} for 1, 2, 3. Blocks by h: {block} | gate_v2, addenda 3 to 5 |",
           f"| e | {a5['item_e']['rule']}. Can fail on: {', '.join(a6['item_e_application']['can_fail_the_gate_on'])}. On development folds: {a6['item_e_application']['on_development_folds']} | addenda 5, 6 |",
           f"| f | {g['f']} | gate_v2 |",
           f"| g | {g['g']['rule']}. X_h %: {x}. {a3['item_g']['option'].upper() and 'Option (a)'}: {a3['item_g']['rule']} | gate_v2, addendum 3 |",
           f"| b (report-only) | {g['b']} | gate_v2, addendum 3 |", f"| c (report-only) | {g['c']} | gate_v2, addendum 3 |", "",
           "## Other rules in force", "",
           f"- **Skip rule, development and validation:** {g2['skip_rule']['A']}.",
           f"- **Skip rule, forward:** {a1['forward_skip_rule']['skip']}. {a1['forward_skip_rule']['no_skip']}. Registry: {a1['forward_skip_rule']['registry']}. Source: {a1['forward_skip_rule']['list_source']}.",
           f"- **Timing:** {a2['decision_2_timing']['rule']}. Baselines: {a3['timing_parity']['rule']}.",
           f"- **Multiple testing:** {a3['multiple_testing']['rule']}. Forward specs: {a3['multiple_testing']['forward_specs']}.",
           f"- **Horizons:** primary {a5['horizons']['primary']}; {a5['horizons']['low_power_under_item_e']['horizons']} are {a5['horizons']['low_power_under_item_e']['status']}, labelled \"{a5['horizons']['low_power_under_item_e']['label']}\".",
           f"- **Validation:** {a4['validation_reads']['calculation']} reads were logged in addendum 4; {a3['validation']['still_once_per_frozen_model_spec'] and 'still once per frozen model spec'}.",
           f"- **Item g existence test:** {a3['item_g']['existence_test']}.",
           f"- **Feature correction:** {', '.join(a7['affected_features'])}: {a7['fix']}.",
           f"- **Model suite:** {m['no_rescue']}.", "",
           "## Sources", "", "| File | Written | Kind | Results seen before it was written | Hash |", "|---|---|---|---|---|"]
    for name, when, kind, seen in SOURCES:
        out.append(f"| [{name}]({name}) | {when} | {kind} | {seen} | `{canonical_hash(ROOT / 'docs' / name)}` |")
    addenda = sum(k == "addendum" for _, _, k, _ in SOURCES)
    out += ["", "## Count", "", f"{len(SOURCES)} frozen files in 2 days: 2 gates, {addenda} addenda and 3 specs. Every rule change came before any model fit; addendum 7, written after results, fixed a bug and changed no rule.", "",
            "**One inconsistency, reported and not changed.** gate_v2 says: \"" + g2["changes"].split(". ")[-1].strip() + "\". The addenda were logged as trial-log events, not trials. Only addendum 7's 3 feature changes were counted as trials.", ""]
    return "\n".join(out)


def main() -> int:
    (ROOT / "docs" / "gate_current.md").write_text(build(), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
