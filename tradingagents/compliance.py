"""Report compliance for Indian-market use: disclaimer and advice-language review.

In India, giving investment advice or publishing research reports for
consideration is regulated by SEBI (Investment Advisers Regulations, 2013;
Research Analysts Regulations, 2014), and SEBI has acted against unregistered
"finfluencers" and against assured-return and past-performance claims. This
framework's output is research and decision support for its user. It must not
read as personalised advice, promise returns, or present an approximation of a
famous investor's method as that investor's call.

What this module does:

- ``DISCLAIMER`` goes on every complete report (markdown and HTML).
- ``review(text)`` finds language regulators treat as red flags (assured or
  guaranteed returns, "risk-free", "sure-shot", certainty claims, claims to
  replicate a named investor) and returns each finding with its line.
- ``compliance_section(text)`` renders the disclaimer plus any findings. The
  text itself is never rewritten: a silent edit would hide what the model
  said; flagging it keeps the report honest and the reader warned.

This is a guard rail, not legal advice. Anyone distributing reports to others,
especially for a fee, should get proper legal and regulatory review.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

DISCLAIMER = (
    "**Disclaimer:** This report is generated by an automated multi-agent research system for "
    "research and educational decision support only. It is not investment advice, a research "
    "report under SEBI (Research Analysts) Regulations, 2014, or a recommendation to buy, sell or "
    "hold any security. The authors are not SEBI-registered investment advisers or research "
    "analysts. Markets carry risk, including loss of capital. Backtests, historical results and "
    "rule-based approximations of well-known investors' published principles do not guarantee "
    "future results and are not those investors' views or trades. Data may be delayed, incomplete "
    "or wrong; verify independently and consult a SEBI-registered investment adviser before acting."
)

# (pattern, why it is a problem). Word-bounded and case-insensitive.
RED_FLAGS: tuple[tuple[str, str], ...] = (
    (r"\b(guaranteed?|assured)\s+(returns?|profits?|gains?|income)\b", "promises returns"),
    (r"\b(returns?|profits?|gains?)\s+(are|is)\s+(guaranteed|assured|certain)\b", "promises returns"),
    (r"\brisk[- ]free\b", "claims no risk"),
    (r"\b(no|zero)\s+risk\b", "claims no risk"),
    (r"\bcan(?:not|'t)\s+(lose|go wrong|fail)\b", "claims no risk"),
    (r"\bsure[- ]?shot\b", "certainty claim"),
    (r"\b(100|hundred)\s*(%|percent)\s+(sure|certain|accurate|guaranteed)\b", "certainty claim"),
    (r"\bdefinitely\s+(will\s+)?(go|rise|fall|hit|reach|double)\b", "certainty claim"),
    (r"\bwill\s+(certainly|surely)\b", "certainty claim"),
    (r"\b(jackpot|multibagger\s+guaranteed|double\s+your\s+money)\b", "promotional claim"),
    (r"\b(buffett|jhunjhunwala|damani|kedia|lynch|graham|o'?neil|minervini)\s+(would|is|has been)\s+"
     r"(buy|buying|sell|selling|recommend)", "attributes a call to a named investor"),
)
_COMPILED = tuple((re.compile(p, re.IGNORECASE), why) for p, why in RED_FLAGS)


@dataclass(frozen=True)
class Finding:
    line: int
    phrase: str
    reason: str


# "there are no guaranteed returns" is the opposite of a promise.
_NEGATION = re.compile(r"\b(no|not|never|without|nor|isn't|aren't|cannot)\b[\w\s,'-]{0,12}$", re.IGNORECASE)


def review(text: str) -> list[Finding]:
    findings = []
    for number, line in enumerate((text or "").splitlines(), 1):
        for pattern, why in _COMPILED:
            for match in pattern.finditer(line):
                if _NEGATION.search(line[: match.start()]):
                    continue
                findings.append(Finding(number, match.group(0), why))
    return findings


def compliance_section(text: str) -> str:
    """The closing section of a report: findings (if any) and the disclaimer."""
    lines = ["## Compliance and risk disclaimer", ""]
    findings = review(text)
    if findings:
        lines.append(f"Automated review flagged {len(findings)} phrase(s) that read as promises or "
                     "certainty. Treat them as the model's overstatement, not as fact:")
        lines.append("")
        lines += [f"- line {f.line}: “{f.phrase}” ({f.reason})" for f in findings]
        lines.append("")
    lines.append(DISCLAIMER)
    return "\n".join(lines)
